export function resolveTheme(themeId: string): ThemeDefinition {
  if (themeId === 'auto') {
    const prefersDark =
      typeof window !== 'undefined' &&
      window.matchMedia?.('(prefers-color-scheme: dark)').matches;
    return THEMES.find((t) => t.id === (prefersDark ? 'obsidian-gold' : 'ivory-gold')) || THEMES[0];
  }
  if (themeId === 'light') return THEMES[0];
  if (themeId === 'dark') return THEMES[1];
  return THEMES.find((t) => t.id === themeId) || THEMES[0];
}

export function applyThemeToDocument(themeId: string): ThemeDefinition {
  const theme = resolveTheme(themeId);
  const root = document.documentElement;
  root.setAttribute('data-theme', theme.id);
  root.setAttribute('data-theme-style', theme.styleVariant);
  root.setAttribute('data-color-scheme', theme.isDark ? 'dark' : 'light');
  root.style.colorScheme = theme.isDark ? 'dark' : 'light';
  Object.entries(theme.vars).forEach(([key, val]) => {
    if (key === '--meta-theme') return;
    root.style.setProperty(key, val);
  });
  const meta = document.querySelector('meta[name="theme-color"]');
  if (meta) meta.setAttribute('content', theme.vars['--meta-theme']);
  return theme;
}
